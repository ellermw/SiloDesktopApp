    public static string T(string key, params (string Name, object? Value)[] values)
    {
        var table = values.Any(value => value.Name == "count" && Convert.ToString(value.Value, CultureInfo.InvariantCulture) == "1") && Singular.ContainsKey(key) ? Singular : English;
        var text = table.GetValueOrDefault(key, key);
        foreach (var (name, value) in values) text = text.Replace("{" + name + "}", Convert.ToString(value, CultureInfo.CurrentCulture) ?? "", StringComparison.Ordinal);
        return text;
    }
