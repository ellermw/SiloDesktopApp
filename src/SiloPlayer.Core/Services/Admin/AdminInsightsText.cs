    public static string T(string key, params (string Name, object? Value)[] values)
    {
        var arguments = new Dictionary<string, object?>(StringComparer.Ordinal);
        foreach (var (name, value) in values) arguments[name] = value;
        if (English.TryGetValue(key, out var pattern) || Native.TryGetValue(key, out pattern)) return AdminText.Format(pattern, arguments);
        return AppStrings.Get(key, arguments, fallback: key);
    }

    /// <summary>The arguments of an official count message: <c>count</c> for the plural and <c>count_text</c> in the interface locale's digits.</summary>
    public static (string, object?)[] Count(long count) => AdminPlaybackAuditText.Count(count);
