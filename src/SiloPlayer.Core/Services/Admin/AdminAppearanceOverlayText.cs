    public static string T(string key, params (string Key, object? Value)[] arguments)
    {
        var fallback = English.GetValueOrDefault(key) ?? key;
        foreach (var (name, value) in arguments) fallback = fallback.Replace("{" + name + "}", Convert.ToString(value, AppStrings.FormatCulture));
        return AppStrings.Get(key, arguments.ToDictionary(pair => pair.Key, pair => pair.Value), fallback: fallback);
    }

