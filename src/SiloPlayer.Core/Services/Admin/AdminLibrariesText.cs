    /// <summary>Every key this domain owns, for catalog-coverage tests.</summary>
    public static IReadOnlyCollection<string> Keys { get; } = English.Keys.ToArray();

    public static bool Has(string key) => English.ContainsKey(key);

    /// <summary>Formats a domain key from the English table, or any other key from the localized interface catalog.</summary>
    public static string T(string key, params (string Name, object? Value)[] values)
    {
        var arguments = new Dictionary<string, object?>(StringComparer.Ordinal);
        foreach (var (name, value) in values) arguments[name] = value;
        if (English.TryGetValue(key, out var pattern)) return AdminText.Format(pattern, arguments);
        return AppStrings.Get(key, arguments, fallback: key);
    }

    /// <summary>A count argument pair as the WebUI passes it (<c>count</c> plus a formatted <c>count_text</c>).</summary>
    public static (string, object?)[] Count(long count, params (string Name, object? Value)[] more) =>
        [("count", count), ("count_text", count.ToString("N0", AppStrings.FormatCulture)), .. more];

    /// <summary>
    /// Splits a formatted message on its rich-text tags (<c>&lt;link&gt;…&lt;/link&gt;</c>,
    /// <c>&lt;code&gt;</c>, <c>&lt;button&gt;</c>): each segment's tag is null for plain text.
    /// </summary>
    public static IReadOnlyList<(string Text, string? Tag)> Segments(string formatted)
    {
        var result = new List<(string, string?)>();
        var position = 0;
        while (position < formatted.Length)
        {
            var open = formatted.IndexOf('<', position);
            if (open < 0) { result.Add((formatted[position..], null)); break; }
            var close = formatted.IndexOf('>', open);
            if (close < 0) { result.Add((formatted[position..], null)); break; }
            var tag = formatted[(open + 1)..close];
            var end = formatted.IndexOf("</" + tag + ">", close, StringComparison.Ordinal);
            if (tag.Length == 0 || tag.Contains(' ') || tag.StartsWith('/') || end < 0) { result.Add((formatted[position..(close + 1)], null)); position = close + 1; continue; }
            if (open > position) result.Add((formatted[position..open], null));
            result.Add((formatted[(close + 1)..end], tag));
            position = end + tag.Length + 3;
        }
        return result;
    }

    /// <summary>The formatted message with its tags removed (for accessible names and tooltips).</summary>
    public static string Plain(string formatted) => string.Concat(Segments(formatted).Select(segment => segment.Text));
