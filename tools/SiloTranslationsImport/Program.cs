// Converts the pinned silo-translations release into the desktop's offline catalogs.
//
// Silo-Server/silo-translations owns every interface string and has no Windows
// generator. Its pinned web release is vendored, with its release checksum, in
// the official server repository (web/src/locales, recorded by .silo-translations).
// This tool reads that generated output at an exact, clean server commit and
// rewrites each shipped language's precompiled ICU messages into a compact form
// the desktop formatter reads. It never changes message text: literals, argument
// names, plural/select options and tags are copied exactly. Generated files and
// their checksums are recorded in catalog-manifest.json; never edit them by hand.
//
// Usage (from the repository root):
//   dotnet run --project tools/SiloTranslationsImport -- --server <silo-server checkout> --commit <sha>
//     [--out src/SiloPlayer.Core/Localization/Generated] [--exclude-prefix web.admin.]

using System.Diagnostics;
using System.Security.Cryptography;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;

var options = ParseArguments(args);
var server = Path.GetFullPath(options.GetValueOrDefault("--server") ?? Fail<string>("--server is required"));
var commit = options.GetValueOrDefault("--commit") ?? Fail<string>("--commit is required");
var output = Path.GetFullPath(options.GetValueOrDefault("--out") ?? Path.Combine("src", "SiloPlayer.Core", "Localization", "Generated"));
var excluded = (options.GetValueOrDefault("--exclude-prefix") ?? "web.admin.")
    .Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);

var head = Git(server, "rev-parse", "HEAD").Trim();
if (!string.Equals(head, commit, StringComparison.OrdinalIgnoreCase))
    return Fail<int>($"server checkout is at {head}, not the pinned {commit}");
if (Git(server, "status", "--porcelain", "--", "web/src/locales", ".silo-translations", ".silo-translations-files").Trim().Length != 0)
    return Fail<int>("the server's generated locale files differ from the commit; use a clean checkout");

var record = File.ReadAllLines(Path.Combine(server, ".silo-translations"))
    .Select(line => line.Split('=', 2)).Where(parts => parts.Length == 2)
    .ToDictionary(parts => parts[0], parts => parts[1], StringComparer.Ordinal);
if (record.GetValueOrDefault("platform") != "web") return Fail<int>(".silo-translations is not the web platform record");
var release = record.GetValueOrDefault("version") ?? Fail<string>(".silo-translations has no version");
var releaseSha = record.GetValueOrDefault("sha256") ?? Fail<string>(".silo-translations has no sha256");
if (release.StartsWith("local-", StringComparison.Ordinal)) return Fail<int>("the server is pinned to a local catalog build, not a release");

var locales = Path.Combine(server, "web", "src", "locales");
var keysText = File.ReadAllText(Path.Combine(locales, "keys.ts"));
var header = Regex.Match(keysText, @"^// Generated by silo-translations (\S+) from catalog/\*\.arb; do not edit\.");
if (!header.Success || header.Groups[1].Value != release)
    return Fail<int>($"keys.ts was not generated by release {release}");
var languages = Regex.Matches(keysText,
        @"\{\s*tag:\s*""(?<tag>[^""]+)"",\s*name:\s*""(?<name>[^""]+)"",\s*dir:\s*""(?<dir>ltr|rtl)"",\s*pseudo:\s*(?<pseudo>true|false)\s*\}")
    .Where(match => match.Groups["pseudo"].Value == "false")
    .Select(match => (Tag: match.Groups["tag"].Value, Name: match.Groups["name"].Value, Dir: match.Groups["dir"].Value))
    .ToList();
if (languages.Count == 0 || languages[0].Tag != "en") return Fail<int>("keys.ts LOCALES must list English first");

Directory.CreateDirectory(output);
var manifestLanguages = new JsonArray();
HashSet<string>? englishKeys = null;
foreach (var language in languages)
{
    var sourcePath = Path.Combine(locales, language.Tag + ".json");
    var sourceBytes = File.ReadAllBytes(sourcePath);
    var source = JsonNode.Parse(sourceBytes)!.AsObject();
    var builder = new StringBuilder("{\n");
    var count = 0;
    foreach (var key in source.Select(pair => pair.Key).Where(key => !excluded.Any(prefix => key.StartsWith(prefix, StringComparison.Ordinal)))
                 .OrderBy(key => key, StringComparer.Ordinal))
    {
        if (count++ > 0) builder.Append(",\n");
        builder.Append(Json(JsonValue.Create(key))).Append(':').Append(Json(Message(source[key]!.AsArray(), $"{language.Tag}:{key}")));
    }
    builder.Append("\n}\n");
    var keys = source.Select(pair => pair.Key).ToHashSet(StringComparer.Ordinal);
    if (englishKeys == null) englishKeys = keys;
    else if (keys.Except(englishKeys).FirstOrDefault() is { } extra) return Fail<int>($"{language.Tag} has {extra}, which English lacks");
    var outputBytes = new UTF8Encoding(false).GetBytes(builder.ToString());
    File.WriteAllBytes(Path.Combine(output, language.Tag + ".json"), outputBytes);
    manifestLanguages.Add(new JsonObject
    {
        ["tag"] = language.Tag,
        ["name"] = language.Name,
        ["dir"] = language.Dir,
        ["messages"] = count,
        ["source"] = "web/src/locales/" + language.Tag + ".json",
        ["source_sha256"] = Sha(sourceBytes),
        ["output"] = language.Tag + ".json",
        ["output_sha256"] = Sha(outputBytes),
    });
    Console.WriteLine($"{language.Tag}: {count} messages");
}

var manifest = new JsonObject
{
    ["format"] = 1,
    ["generator"] = "tools/SiloTranslationsImport",
    ["catalog_owner"] = "https://github.com/Silo-Server/silo-translations",
    ["catalog_release"] = release,
    ["catalog_release_platform"] = "web",
    ["catalog_release_tarball_sha256"] = releaseSha,
    ["source_repository"] = "https://github.com/Silo-Server/silo-server",
    ["source_commit"] = head,
    ["source_path"] = "web/src/locales",
    ["source_keys_sha256"] = Sha(File.ReadAllBytes(Path.Combine(locales, "keys.ts"))),
    ["excluded_key_prefixes"] = new JsonArray(excluded.Select(prefix => (JsonNode)JsonValue.Create(prefix)!).ToArray()),
    ["languages"] = manifestLanguages,
};
File.WriteAllText(Path.Combine(output, "catalog-manifest.json"),
    manifest.ToJsonString(new JsonSerializerOptions { WriteIndented = true, Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping }).Replace("\r\n", "\n") + "\n",
    new UTF8Encoding(false));
Console.WriteLine($"Wrote {languages.Count} languages from silo-translations {release} (server {head}) to {output}");
return 0;

// A message is an array of FormatJS elements. A message that is one literal is
// written as that string; otherwise each element becomes a literal string or
// one of: {"a":name} argument, {"n":name} number, {"h":0} plural #,
// {"s":name,"o":{...}} select, {"p":name,"o":{...}} cardinal plural, {"g":name,"c":[...]} tag.
static JsonNode Message(JsonArray elements, string where)
{
    var converted = Elements(elements, where);
    return converted.Count == 1 && converted[0] is JsonValue value && value.TryGetValue<string>(out _) ? value.DeepClone() : converted;
}

static JsonArray Elements(JsonArray elements, string where)
{
    var result = new JsonArray();
    foreach (var element in elements)
    {
        var item = element!.AsObject();
        var type = item["type"]!.GetValue<int>();
        string Name() => item["value"]!.GetValue<string>();
        switch (type)
        {
            case 0: result.Add(Name()); break;
            case 1: result.Add(new JsonObject { ["a"] = Name() }); break;
            case 2:
                if (item["style"] is not null) throw new InvalidDataException($"{where}: number style is not supported");
                result.Add(new JsonObject { ["n"] = Name() }); break;
            case 5: result.Add(new JsonObject { ["s"] = Name(), ["o"] = Options(item, where) }); break;
            case 6:
                if (item["pluralType"]?.GetValue<string>() is { } kind && kind != "cardinal")
                    throw new InvalidDataException($"{where}: {kind} plurals are not supported");
                if (item["offset"] is { } offset && offset.GetValue<int>() != 0)
                    throw new InvalidDataException($"{where}: plural offsets are not supported");
                result.Add(new JsonObject { ["p"] = Name(), ["o"] = Options(item, where) }); break;
            case 7: result.Add(new JsonObject { ["h"] = 0 }); break;
            case 8: result.Add(new JsonObject { ["g"] = Name(), ["c"] = Elements(item["children"]!.AsArray(), where) }); break;
            default: throw new InvalidDataException($"{where}: element type {type} is not supported");
        }
    }
    return result;
}

static JsonObject Options(JsonObject item, string where)
{
    var result = new JsonObject();
    foreach (var (name, option) in item["options"]!.AsObject())
        result[name] = Elements(option!["value"]!.AsArray(), where);
    return result;
}

static string Json(JsonNode? node) => node!.ToJsonString(new JsonSerializerOptions { Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping });

static string Sha(byte[] bytes) => Convert.ToHexString(SHA256.HashData(bytes)).ToLowerInvariant();

static string Git(string directory, params string[] arguments)
{
    var start = new ProcessStartInfo("git") { RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false };
    // Read-only: never refresh the reference checkout's index.
    start.ArgumentList.Add("--no-optional-locks");
    start.ArgumentList.Add("-C"); start.ArgumentList.Add(directory);
    foreach (var argument in arguments) start.ArgumentList.Add(argument);
    using var process = Process.Start(start)!;
    var text = process.StandardOutput.ReadToEnd();
    process.WaitForExit();
    if (process.ExitCode != 0) throw new InvalidOperationException($"git {string.Join(' ', arguments)} failed: {process.StandardError.ReadToEnd()}");
    return text;
}

static Dictionary<string, string> ParseArguments(string[] arguments)
{
    var result = new Dictionary<string, string>(StringComparer.Ordinal);
    for (var index = 0; index < arguments.Length; index += 2)
    {
        if (index + 1 >= arguments.Length || !arguments[index].StartsWith("--", StringComparison.Ordinal))
            throw new ArgumentException($"expected --name value pairs, got {arguments[index]}");
        result[arguments[index]] = arguments[index + 1];
    }
    return result;
}

static T Fail<T>(string message)
{
    Console.Error.WriteLine("SiloTranslationsImport: " + message);
    Environment.Exit(1);
    return default!;
}
